const dictionaries: Record<Language, Record<Key, string>> = { es, en };

function initial(): Language {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem('idioma');
  } catch {
  }
  return languageFor(saved, navigator.language);
}

export const i18n = $state({ language: initial() });

export function setLanguage(i: Language) {
  i18n.language = i;
  document.documentElement.lang = i;
  try {
    localStorage.setItem('idioma', i);
  } catch {
  }
}

export function t(key: Key, p: Record<string, string | number> = {}): string {
  const base = dictionaries[i18n.language][key] ?? es[key] ?? key;
  return base.replace(/\{(\w+)\}/g, (_, k) => String(p[k] ?? `{${k}}`));
}

export function kindText(tp: ModKind) {
  return t(`kind.${tp}` as Key);
}

export function ruleText(a: Pick<Edge, 'before' | 'after' | 'rule'>) {
  return t(`rule.${a.rule}` as Key, { a: a.before, b: a.after });
}

export function fixText(a: Fix): string {
  const s = a.action === 'MoveToSection' ? a.data[1] || t('sections.none') : '';
  return t(`conflict.fix.${a.action}` as Key, { d: fixMod(a), s });
}

export function fixMod(a: Fix): string {
  if (a.action === 'Win' || a.action === 'Keep' || a.action === 'MoveToSection') return a.data[0];
  if (a.action === 'Accept') return '';
  return 'data' in a ? String(a.data) : '';
}

export function fixHelp(a: Fix): string | undefined {
  if (a.action === 'Win') return t('conflict.fix.Win_help', { d: a.data[0], r: a.data[1].map((x) => `«${x}»`).join(', ') });
  if (a.action === 'Accept') return t('conflict.fix.Accept_help');
  if (a.action === 'Keep') return t('conflict.fix.Keep_help', { r: a.data[1].map((x) => `«${x}»`).join(', ') });
  if (a.action === 'MoveToSection') return t('conflict.fix.MoveToSection_help');
  return undefined;
}

export function pairText(p: Pair): string {
  const en = i18n.language === 'en';
  const parts: string[] = [];
  if (en) {
    parts.push(
      p.total ? `“${p.wins}” overrides “${p.loses}” in ${p.total} file(s)` : `“${p.wins}” and “${p.loses}” share files`,
    );
    if (p.total_lost) parts.push(`“${p.loses}” loses ${p.total_lost} script object(s)`);
    if (p.identical) parts.push(`${p.identical} identical`);
    if (p.total_not_load) parts.push(`${p.total_not_load} the game doesn’t load`);
    if (p.related) parts.push('one requires the other or both come from the same Workshop item, likely intended');
    else if (p.accepted) parts.push('you kept it this way');
  } else {
    parts.push(
      p.total ? `«${p.wins}» pisa a «${p.loses}» en ${p.total} archivo(s)` : `«${p.wins}» y «${p.loses}» comparten archivos`,
    );
    if (p.total_lost) parts.push(`«${p.loses}» pierde ${p.total_lost} objeto(s) de script`);
    if (p.identical) parts.push(`${p.identical} idénticos`);
    if (p.total_not_load) parts.push(`${p.total_not_load} que el juego no carga`);
    if (p.related) parts.push('uno requiere al otro o son del mismo elemento del Workshop: seguramente es a propósito');
    else if (p.accepted) parts.push('lo diste por bueno');
  }
  return parts.join(' · ');
}

