export function findingCause(h: Finding, id: string): string {
  const en = i18n.language === 'en';
  const x = h.kind;
  switch (x.kind) {
    case 'MissingDependency':
      if (!x.inactive_installed) return en ? `needs ${x.requires}` : `falta ${x.requires}`;
      return h.severity === 'Blocks' ? (en ? `${x.requires} won’t load` : `${x.requires} no carga`) : en ? `${x.requires} off` : `${x.requires} inactivo`;
    case 'ModNotFound':
      return en ? 'not installed' : 'no instalado';
    case 'WontLoad': {
      const root = x.because[x.because.length - 1];
      return en ? `${root} won’t load` : `${root} no carga`;
    }
    case 'RequireTypo':
      return en ? 'require misspelled' : 'require mal escrito';
    case 'Cycle':
      return en ? 'order cycle' : 'ciclo de orden';
    case 'DuplicatedId':
      return en ? 'installed twice' : 'instalado dos veces';
    case 'Incompatible':
      return en ? 'incompatible' : 'incompatible';
    case 'GameVersion':
      return en ? `for game ${x.min ?? '…'}–${x.max ?? '…'}` : `para el juego ${x.min ?? '…'}–${x.max ?? '…'}`;
    case 'OnlyB41':
      return en ? 'Build 41 only' : 'solo Build 41';
    case 'NoValidFolder':
      return en ? `no folder for ${x.game}` : `sin carpeta para ${x.game}`;
    case 'OverriddenFiles': {
      const lost = x.pairs.filter((p) => p.loses === id).reduce((n, p) => n + p.total_lost, 0);
      if (lost) return en ? `loses ${lost} script object(s)` : `pierde ${lost} objeto(s) de script`;
      const lose = x.pairs.filter((p) => p.loses === id).reduce((n, p) => n + p.total, 0);
      const win = x.pairs.filter((p) => p.wins === id).reduce((n, p) => n + p.total, 0);
      if (lose) return en ? `loses ${lose} file(s)` : `pierde ${lose} archivo(s)`;
      if (win) return en ? `wins ${win} file(s)` : `gana ${win} archivo(s)`;
      return en ? 'shares files' : 'comparte archivos';
    }
    case 'OverridesGame':
      return en ? `replaces ${x.total} game file(s)` : `sustituye ${x.total} del juego`;
    case 'TiledefRepeated':
      return en ? `tiledef ${x.num} repeated` : `tiledef ${x.num} repetido`;
    case 'LuaGlobalReplaced':
      return en ? `${x.total} Lua function(s) cut off` : `${x.total} función(es) Lua anuladas`;
    case 'JavaLinkBroken':
      return en ? `Java for another game version` : `Java de otra versión del juego`;
    case 'ScriptRedefined':
      return x.total
        ? x.properties.length
          ? en ? `changes ${x.properties.slice(0, 2).join(', ')}` : `cambia ${x.properties.slice(0, 2).join(', ')}`
          : en ? `${x.total} script object(s)` : `${x.total} objeto(s) de script`
        : en ? 'identical scripts' : 'scripts idénticos';
    case 'MapCellsShared':
      return x.squares === 0 ? (en ? 'map cells, no overlap' : 'celdas sin pisarse') : en ? 'overlapping maps' : 'mapas que se pisan';
    case 'MapOverTown':
      return en ? 'map over a town' : 'mapa sobre un pueblo';
    case 'ZbNotInstalled':
      return en ? 'needs ZombieBuddy' : 'falta ZombieBuddy';
    case 'ZbVersion': {
      const min = x.ranges.map(([a]) => a).find((a) => a);
      return min ? (en ? `needs ZB ${min}+` : `pide ZB ${min}+`) : en ? `not for ZB ${x.zb}` : `no vale para ZB ${x.zb}`;
    }
    case 'ZbJarInvalid':
      return en ? 'invalid JAR' : 'JAR no válido';
    case 'ZbJarMissing':
      return en ? 'JAR missing' : 'falta el JAR';
    case 'ZbRepeatedPackage':
      return en ? 'same Java package' : 'paquete Java repetido';
    case 'ZbIncompatibleGame':
      return en ? 'ZombieBuddy too old' : 'ZombieBuddy antiguo';
    case 'ZbApproval':
      return x.state === 'Denied' ? (en ? 'denied in ZB' : 'denegado en ZB') : en ? 'not approved' : 'sin aprobar';
    case 'ZbModNotEnabled':
      return en ? 'ZombieBuddy off' : 'ZombieBuddy inactivo';
    case 'JavaPatchOverlap':
      return en ? 'same game method' : 'mismo método del juego';
    case 'SectionOrder':
      return en ? `${x.needs} in a later section` : `${x.needs} en una sección posterior`;
    case 'SectionSoftRule':
      return en ? `after ${x.after}: not applied` : `tras ${x.after}: no se aplica`;
    case 'ModifiedInstall':
      return en ? 'game modified' : 'juego modificado';
  }
}

function versionRange(min: string | null, max: string | null): string {
  if (min && min === max) return min;
  return t('common.range', { a: min ?? '…', b: max ?? '…' });
}

export function whyText(h: Finding): string {
  const x = h.kind;
  const q = (s: string) => (i18n.language === 'en' ? `“${s}”` : `«${s}»`);
  switch (x.kind) {
    case 'OnlyB41':
      return t('conflict.why.b41');
    case 'GameVersion':
      return t('conflict.why.version', { r: versionRange(x.min, x.max), g: x.game });
    case 'NoValidFolder':
      return t('conflict.why.nofolder', { g: x.game });
    case 'ModNotFound':
      return t('conflict.why.notfound');
    case 'MissingDependency':
      return t(x.inactive_installed ? (h.severity === 'Blocks' ? 'conflict.why.missing_broken' : 'conflict.why.missing_off') : 'conflict.why.missing_none', { r: x.requires });
    case 'WontLoad':
      return t('conflict.why.wontload', { c: x.because.map(q).join(' → ') });
    default:
      return findingText(h);
  }
}

export function clusterTitle(c: Cluster): string {
  const n = c.entries.length;
  const h = c.entries[0].findings[0];
  const x = h.kind;
  switch (x.kind) {
    case 'OnlyB41':
      return t('conflict.cluster.b41', { n });
    case 'GameVersion':
      return t('conflict.cluster.version', { n, g: x.game });
    case 'NoValidFolder':
      return t('conflict.cluster.nofolder', { n, g: x.game });
    case 'ModNotFound':
      return t('conflict.cluster.notfound', { n });
    case 'RequireTypo':
      return t('conflict.cluster.typo', { n });
    case 'MissingDependency':
      return t(x.inactive_installed ? (h.severity === 'Blocks' ? 'conflict.cluster.missing_broken' : 'conflict.cluster.missing_off') : 'conflict.cluster.missing_none', { n, r: x.requires });
    case 'WontLoad':
      return t('conflict.cluster.wontload', { n, r: x.because[x.because.length - 1] ?? '' });
    default:
      return findingText(h);
  }
}

